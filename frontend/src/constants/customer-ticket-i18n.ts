export function normalizeCustomerTicketLanguage(value?: string | null): CustomerTicketLanguage | null {
  if (!value) return null
  const normalized = value.toLowerCase()
  if (normalized === 'zh' || normalized === 'zh-cn' || normalized.startsWith('zh-')) return 'zh-CN'
  if (normalized === 'en' || normalized === 'en-us' || normalized.startsWith('en-')) return 'en-US'
  return null
}

export function resolveCustomerTicketLanguage(): CustomerTicketLanguage {
  const params = new URLSearchParams(window.location.search)
  const urlLanguage = normalizeCustomerTicketLanguage(params.get('lang'))
  if (urlLanguage) return urlLanguage

  const storedLanguage = normalizeCustomerTicketLanguage(window.localStorage.getItem(CUSTOMER_TICKET_LANGUAGE_STORAGE_KEY))
  if (storedLanguage) return storedLanguage

  return 'en-US'
}

export function createCustomerTicketTranslator(language: CustomerTicketLanguage): CustomerTicketTranslator {
  return (key, vars) => {
    const template = messages[language][key] || messages['zh-CN'][key] || key
    return Object.entries(vars || {}).reduce((text, [name, value]) => {
      return text.replaceAll(`{${name}}`, String(value ?? ''))
    }, template)
  }
}
